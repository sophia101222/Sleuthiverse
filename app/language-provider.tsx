const en:Record<string,string>=Object.fromEntries(Object.entries(zh).map(([a,b])=>[b,a]));
function translate(root:ParentNode,language:Lang){
 const dict=language==="zh"?zh:en;
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
 let node:Node|null;
 while((node=walker.nextNode())){const raw=node.textContent??"";const key=raw.trim();if(dict[key]){const leading=raw.match(/^\s*/)?.[0]??"";const trailing=raw.match(/\s*$/)?.[0]??"";node.textContent=leading+dict[key]+trailing;}}
 if(root instanceof HTMLElement||root instanceof Document){const els=root instanceof Document?[root.documentElement,...Array.from(root.querySelectorAll<HTMLElement>("input,textarea,button,[aria-label],[title]"))]:[root as HTMLElement,...Array.from((root as HTMLElement).querySelectorAll<HTMLElement>("input,textarea,button,[aria-label],[title]"))];for(const el of els){for(const attr of ["placeholder","aria-label","title"]){const v=el.getAttribute(attr);if(v&&dict[v])el.setAttribute(attr,dict[v]);}}}
}
export function LanguageProvider({children}:{children:React.ReactNode}){
 const [language,setLanguage]=useState<Lang>("en");const [ready,setReady]=useState(false);
 useEffect(()=>{const v=localStorage.getItem("sleuthiverse-language");if(v==="zh"||v==="en")setLanguage(v);setReady(true)},[]);
 useEffect(()=>{if(!ready)return;document.documentElement.lang=language;translate(document,language);const observer=new MutationObserver(records=>{for(const r of records){if(r.type==="attributes"&&r.target instanceof HTMLElement){const attr=r.attributeName;const v=attr?r.target.getAttribute(attr):null;const dict=language==="zh"?zh:en;if(attr&&v&&dict[v])r.target.setAttribute(attr,dict[v]);}if(r.type==="characterData"&&r.target.nodeType===Node.TEXT_NODE){const raw=r.target.textContent??"";const key=raw.trim();const dict=language==="zh"?zh:en;if(dict[key])r.target.textContent=raw.replace(key,dict[key]);}r.addedNodes.forEach(n=>{if(n.nodeType===Node.TEXT_NODE){const raw=n.textContent??"";const key=raw.trim();const dict=language==="zh"?zh:en;if(dict[key])n.textContent=raw.replace(key,dict[key]);}else if(n.nodeType===Node.ELEMENT_NODE)translate(n as Element,language);});}});observer.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:["placeholder","aria-label","title"]});return()=>observer.disconnect()},[language,ready]);
 const value=useMemo(()=>({language,toggle:()=>setLanguage(old=>{const next=old==="en"?"zh":"en";localStorage.setItem("sleuthiverse-language",next);return next})}),[language]);
 return <C.Provider value={value}>{children}</C.Provider>;
}
